import { expect, test } from '@playwright/test'

test('editor signs in, creates, finds, views, edits and signs out of the real catalog', async ({ page }, testInfo) => {
  await page.goto('/products')
  await page.getByLabel('Username').fill('e2e-catalog-editor')
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Products', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Add product' }).click()
  const sku = `E2E-${Date.now()}`
  await page.getByLabel('Product name').fill('Warehouse shelving bracket')
  await page.getByLabel('SKU', { exact: false }).fill(sku)
  await page.getByLabel('Category', { exact: false }).fill('Hardware')
  await page.getByLabel('Description').fill('Fictional product created by the automated TRD-13 browser test.')
  await page.getByRole('button', { name: 'Save product' }).click()
  await expect(page.getByText('Product created successfully.', { exact: true })).toBeVisible()
  await page.getByLabel('Search products').fill(sku)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('link', { name: 'Warehouse shelving bracket', exact: true }).click()
  await expect(page.getByText(sku, { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Edit product', exact: true }).click()
  await page.getByLabel('Product name').fill('Heavy-duty shelving bracket')
  await page.getByLabel('Active product', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Save product' }).click()
  await expect(page.getByText('Product updated successfully.', { exact: true })).toBeVisible()
  await page.getByLabel('Search products').fill(sku)
  await page.getByLabel('Status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Heavy-duty shelving bracket', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Inactive', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('product-catalog.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Products', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('product-catalog-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  await page.goto('/products')
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
})

test('invalid credentials show a useful error without opening the workspace', async ({ page }) => {
  await page.goto('/products/new')
  await page.getByLabel('Username').fill('e2e-catalog-editor')
  await page.getByLabel('Password', { exact: true }).fill('deliberately-incorrect-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('username or password is incorrect')
  await expect(page.getByRole('heading', { name: 'Add product' })).not.toBeVisible()
})
