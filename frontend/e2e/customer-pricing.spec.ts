import { expect, test } from '@playwright/test'

test('sales employee manages customers and exact LKR selling prices end to end', async ({ page }, testInfo) => {
  const suffix = Date.now().toString()
  const customerName = `Fictional sales customer ${suffix}`
  const productName = `Sales test bolt ${suffix}`
  await page.goto('/customers')
  await page.getByLabel('Username').fill('e2e-catalog-editor')
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Add customer' }).click()
  await page.getByLabel('Customer name').fill(customerName)
  await page.getByLabel('Contact person').fill('Fictional test contact')
  await page.getByLabel('Email', { exact: true }).fill('sales@example.test')
  await page.getByLabel('Address', { exact: true }).fill('Fictional test address')
  await page.getByRole('button', { name: 'Save customer' }).click()
  await expect(page.getByText('Customer created successfully.', { exact: true })).toBeVisible()
  await page.getByLabel('Search customers').fill(customerName)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('link', { name: customerName, exact: true }).click()
  await page.getByRole('link', { name: 'Edit customer', exact: true }).click()
  await page.getByLabel('Phone', { exact: true }).fill('+94 11 000 0000')
  await page.getByRole('button', { name: 'Save customer' }).click()
  await expect(page.getByText('Customer updated successfully.', { exact: true })).toBeVisible()
  await page.getByLabel('Search customers').fill(customerName)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('cell', { name: '+94 11 000 0000', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('customers.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('customers-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 720 })

  await page.getByRole('link', { name: 'Products', exact: true }).click()
  await page.getByRole('link', { name: 'Add product' }).click()
  await page.getByLabel('Product name').fill(productName)
  await page.getByLabel('SKU', { exact: false }).fill(`SALES-${suffix}`)
  await page.getByLabel('Category', { exact: false }).fill('Hardware')
  await page.getByRole('button', { name: 'Save product' }).click()
  await expect(page.getByText('Product created successfully.', { exact: true })).toBeVisible()
  await page.getByLabel('Search products').fill(productName)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('link', { name: productName, exact: true }).click()
  await expect(page.getByText('Not set', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Manage selling price' }).click()
  await page.getByLabel('New selling price (LKR)').fill('1234.56')
  await page.getByRole('button', { name: 'Save selling price' }).click()
  await expect(page.getByText('Selling price updated successfully.', { exact: true })).toBeVisible()
  await expect(page.getByText('LKR 1,234.56 per Each', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('selling-price.png'), fullPage: true })
  await page.getByLabel('New selling price (LKR)').fill('0.001')
  await page.getByRole('button', { name: 'Save selling price' }).click()
  await expect(page.getByRole('alert')).toContainText('Check the highlighted selling price.')
  await page.getByLabel('New selling price (LKR)').fill('0')
  await page.getByRole('button', { name: 'Save selling price' }).click()
  await expect(page.getByText('LKR 0.00 per Each', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('LKR 0.00 per Each', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
})
